/**
 * SIH26025 Data Provenance & Integrity Classification
 * 
 * Safety & Scientific Truth Mandate:
 * Every data point, risk calculation, alert, and map feature must be
 * explicitly tagged with its source classification. Synthetic or simulated
 * data must never masquerade as real field data.
 */

export type DataProvenance =
  | 'LIVE'
  | 'SIMULATED'
  | 'DEMO'
  | 'HISTORICAL'
  | 'EXTERNAL'
  | 'EXPERIMENTAL'
  | 'ASSUMPTION';

