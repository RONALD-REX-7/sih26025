export function isValidProvenance(value: unknown): value is DataProvenance {
  return typeof value === 'string' && DATA_PROVENANCES.includes(value as DataProvenance);
}

export function getProvenanceConfig(provenance: DataProvenance): ProvenanceBadgeConfig {
  return PROVENANCE_CONFIGS[provenance] ?? PROVENANCE_CONFIGS.DEMO;
}
